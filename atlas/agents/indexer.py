from __future__ import annotations

import frontmatter

from atlas import config


def rebuild_index() -> None:
    """Regenerate universe/index/MOC.md: one map-of-content file listing every
    concept, its primary member notes, and any notes that merely touch on it.

    Deterministic, not LLM-written -- this is exactly the kind of auto-maintained
    index Karpathy's post points to as the reason fancy RAG/embeddings aren't
    needed at personal-wiki scale.
    """
    library_dir = config.vault_path("library")
    concepts_dir = config.vault_path("concepts")

    primary_by_concept: dict[str, list[str]] = {}
    related_by_concept: dict[str, list[str]] = {}
    for note_path in sorted(library_dir.glob("*.md")):
        post = frontmatter.load(note_path)
        for concept_slug in post.get("concepts", []):
            primary_by_concept.setdefault(concept_slug, []).append(note_path.stem)
        for concept_slug in post.get("related_concepts", []):
            related_by_concept.setdefault(concept_slug, []).append(note_path.stem)

    lines = ["# Index", "", "Auto-generated by `atlas ingest`. Do not edit by hand.", ""]
    for concept_path in sorted(concepts_dir.glob("*.md")):
        slug = concept_path.stem
        title = frontmatter.load(concept_path).get("title", slug.replace("-", " ").title())
        lines.append(f"## [[concepts/{slug}|{title}]]")
        for note_slug in sorted(primary_by_concept.get(slug, [])):
            note_title = frontmatter.load(library_dir / f"{note_slug}.md").get("title", note_slug)
            lines.append(f"- [[library/{note_slug}|{note_title}]]")

        related = sorted(related_by_concept.get(slug, []))
        if related:
            lines.append("")
            lines.append("_Also touches on:_")
            for note_slug in related:
                note_title = frontmatter.load(library_dir / f"{note_slug}.md").get("title", note_slug)
                lines.append(f"- [[library/{note_slug}|{note_title}]]")
        lines.append("")

    (config.vault_path("index") / "MOC.md").write_text("\n".join(lines))
